# Function to count jobs by location
def get_number_of_jobs_L(location):
    number_of_jobs = 0

    for job in data:
        if location.lower() in job["Location"].lower():
            number_of_jobs += 1

    return location, number_of_jobs

# Locations to analyze
locations = [
    "Los Angeles",
    "New York",
    "San Francisco",
    "Washington DC",
    "Seattle",
    "Austin",
    "Detroit"
]

# Count and sort jobs in descending order
results = [get_number_of_jobs_L(location) for location in locations]
results.sort(key=lambda x: x[1], reverse=True)

# Create workbook and worksheet
workbook = openpyxl.Workbook()
worksheet = workbook.active
worksheet.title = "Jobs by Location"

# Add headers
worksheet.append(["Location", "Number of Jobs"])

# Add sorted results
for location, number_of_jobs in results:
    worksheet.append([location, number_of_jobs])

# Create horizontal bar chart
chart = BarChart()
chart.type = "bar"
chart.style = 10
chart.title = "Number of Job Postings by Location"
chart.x_axis.title = "Number of Jobs"
chart.y_axis.title = "Location"
chart.height = 8
chart.width = 15
chart.legend = None

# Select chart data, including header
data_reference = Reference(
    worksheet,
    min_col=2,
    min_row=1,
    max_row=worksheet.max_row
)

# Select location labels
categories_reference = Reference(
    worksheet,
    min_col=1,
    min_row=2,
    max_row=worksheet.max_row
)

chart.add_data(data_reference, titles_from_data=True)
chart.set_categories(categories_reference)

# Put highest job count at the top
chart.y_axis.scaling.orientation = "maxMin"

# IMPORTANT: Attach chart to worksheet
worksheet.add_chart(chart, "D2")

# Save AFTER adding the chart
filename = "job-postings.xlsx"
workbook.save(filename)

print("Excel file saved successfully:", filename)
print("Number of charts created:", len(worksheet._charts))

# Helper function to split multi-select survey responses
def split_responses(data, column):
    temp = data[["Age", column]].dropna().copy()
    temp[column] = temp[column].astype(str).str.split(";")
    temp = temp.explode(column)
    temp[column] = temp[column].str.strip()
    temp = temp[temp[column] != ""]
    return temp



# Helper function to create pie charts for top 5 categories
def plot_top5_pie(column, title):
    query = f"""
    SELECT "{column}"
    FROM main
    WHERE "{column}" IS NOT NULL
    """
    df = pd.read_sql_query(query, conn)

    # Split multiple selections and count each response
    counts = (
        df[column]
        .astype(str)
        .str.split(";")
        .explode()
        .str.strip()
    )

    counts = counts[counts != ""].value_counts().head(5)

    plt.figure(figsize=(8, 8))
    plt.pie(
        counts.values,
        labels=counts.index,
        autopct="%1.1f%%",
        startangle=90
    )
    plt.title(title)
    plt.tight_layout()
    plt.show()



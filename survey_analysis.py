# Convert categorical Age values to numeric values
# Handles values such as "25-34", "35-44", and "65 years or older"
def convert_age(age):
    if pd.isna(age):
        return np.nan

    age = str(age).strip()

    if age.lower() in ["under 18", "under 18 years old"]:
        return 17

    if "prefer not to say" in age.lower() or "not applicable" in age.lower():
        return np.nan

    if "older" in age.lower():
        return 70

    if "-" in age:
        parts = age.split("-")
        try:
            return (float(parts[0]) + float(parts[1])) / 2
        except ValueError:
            return np.nan

    try:
        return float(age)
    except ValueError:
        return np.nan


